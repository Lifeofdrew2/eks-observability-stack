#!/usr/bin/env python3
"""Render Kubernetes objects from the shared Prometheus rules and Grafana dashboards.

The rule files in prometheus/rules/ and the dashboards in grafana/dashboards/
are the single source of truth for both the local Docker Compose stack and
the cluster. This script wraps them as:

  kubernetes/generated/prometheus-rules.yaml   PrometheusRule objects
  kubernetes/generated/grafana-dashboards.yaml ConfigMaps for the Grafana sidecar

Usage:
  python3 scripts/render_k8s.py           # write the files
  python3 scripts/render_k8s.py --check   # fail if the committed files are stale (CI)
"""

import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES_DIR = ROOT / "prometheus" / "rules"
DASH_DIR = ROOT / "grafana" / "dashboards"
OUT_DIR = ROOT / "kubernetes" / "generated"
NAMESPACE = "monitoring"

# kube-prometheus-stack ships its own node alerts; don't duplicate them in-cluster.
SKIP_IN_CLUSTER = {"node-alerts.yml"}

HEADER = "# GENERATED by scripts/render_k8s.py - edit the source files, not this file.\n"


def render_rules() -> str:
    docs = []
    for path in sorted(RULES_DIR.glob("*.yml")):
        if path.name in SKIP_IN_CLUSTER:
            continue
        docs.append(
            {
                "apiVersion": "monitoring.coreos.com/v1",
                "kind": "PrometheusRule",
                "metadata": {
                    "name": f"demo-api-{path.stem}",
                    "namespace": NAMESPACE,
                    "labels": {"app.kubernetes.io/part-of": "eks-observability-stack"},
                },
                "spec": yaml.safe_load(path.read_text()),
            }
        )
    return HEADER + yaml.safe_dump_all(docs, sort_keys=False, width=120)


def render_dashboards() -> str:
    docs = []
    for path in sorted(DASH_DIR.glob("*.json")):
        json.loads(path.read_text())  # fail fast on invalid JSON
        docs.append(
            {
                "apiVersion": "v1",
                "kind": "ConfigMap",
                "metadata": {
                    "name": f"dashboard-{path.stem}",
                    "namespace": NAMESPACE,
                    "labels": {"grafana_dashboard": "1"},
                    "annotations": {"grafana_folder": "Demo Platform"},
                },
                "data": {path.name: path.read_text()},
            }
        )
    return HEADER + yaml.safe_dump_all(docs, sort_keys=False, width=120)


def main() -> int:
    outputs = {
        OUT_DIR / "prometheus-rules.yaml": render_rules(),
        OUT_DIR / "grafana-dashboards.yaml": render_dashboards(),
    }
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"STALE: {p.relative_to(ROOT)} - run: python3 scripts/render_k8s.py")
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for p, text in outputs.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
